/**
 * Creates a clearly-labelled DEMO dataset through the real API (so every
 * validation and approval rule applies). Rates and taxes here are DEMO values
 * for exploring the software — they are not any department's contract terms.
 *
 *   DATABASE_URL=data/demo-db STORAGE_DIR=data/demo-files npm run seed:demo --workspace server
 *
 * Demo user passwords are generated and written to .env.local (gitignored).
 */
import crypto from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';
import { config } from '../config.js';
import { createDb } from '../db/index.js';
import { migrate } from '../db/migrate.js';
import { seedReferenceData } from '../db/seed.js';
import { buildApp } from '../app.js';

const db = await createDb();
await migrate(db);
await seedReferenceData(db);
const app = await buildApp(db);
const tokens: Record<string, string> = {};

async function call(method: string, url: string, body?: unknown, who = 'admin') {
  const res = await app.inject({ method: method as 'POST', url: `/api${url}`, payload: body as object, headers: tokens[who] ? { authorization: `Bearer ${tokens[who]}` } : {} });
  if (res.statusCode >= 300) throw new Error(`${method} ${url} → ${res.statusCode}: ${res.body}`);
  return res.json();
}

const existing = await db.one<{ n: number }>('SELECT count(*)::int AS n FROM app_users');
if (existing!.n > 0) {
  console.log('Database already has users — demo seed skipped.');
  process.exit(0);
}

const pw = () => `Demo-${crypto.randomBytes(9).toString('base64url')}1`;
const creds = { admin: pw(), operator: pw(), approver: pw() };
const setup = await call('POST', '/auth/setup', { email: 'admin@demo.local', name: 'Demo Admin', password: creds.admin });
tokens.admin = setup.token;
for (const role of ['operator', 'approver'] as const) {
  await call('POST', '/users', { email: `${role}@demo.local`, name: `Demo ${role}`, role, password: creds[role] });
  tokens[role] = (await call('POST', '/auth/login', { email: `${role}@demo.local`, password: creds[role] })).token;
}
const envFile = path.join(config.root, '.env.local');
fs.writeFileSync(envFile, `# Demo logins for the DEMO database only (generated by seed-demo)\nDEMO_ADMIN=admin@demo.local ${creds.admin}\nDEMO_OPERATOR=operator@demo.local ${creds.operator}\nDEMO_APPROVER=approver@demo.local ${creds.approver}\n`);

await call('POST', '/suppliers', { name: 'LR Taxi Services Pvt. Ltd. (DEMO profile)', address: 'Enter the real address in System Settings', state_name: 'Delhi', state_code: '07', is_default: true });
const innova = (await call('POST', '/vehicle-categories', { name: 'Innova' })).id;
const dzire = (await call('POST', '/vehicle-categories', { name: 'Dzire' })).id;
const client = (await call('POST', '/clients', { name: 'DEMO Department', short_code: 'DEMO', billing_address: 'Demo address, New Delhi', state_name: 'Delhi', state_code: '07' })).id;
const contract = (await call('POST', '/contracts', {
  client_id: client, title: 'DEMO vehicle hire contract', reference_no: 'DEMO/2025/001', start_date: '2025-04-01', end_date: '2026-03-31', status: 'active',
  invoice_rounding: 'nearest_rupee', bill_no_format: 'LR/{CLIENT}/{FY}/{SEQ}', special_instructions: 'DEMO data — rates and taxes are illustrative only.',
})).id;
for (const [name, type] of [['CGST (DEMO)', 'CGST'], ['SGST (DEMO)', 'SGST']]) {
  const t = await call('POST', `/contracts/${contract}/tax-rules`, { name, tax_type: type, rate: '2.5', effective_from: '2025-04-01', source_ref: 'DEMO — replace with the contract clause' });
  await call('POST', `/tax-rules/${t.id}/approve`, {}, 'approver');
}
const cfg = (base: string) => ({
  billingModel: 'daily_package',
  params: { includedKm: '80', includedHours: '8', hourRounding: { mode: 'ceil', unit: '60' }, night: { enabled: true, start: '22:00', end: '06:00', minOverlapMinutes: 1, countMode: 'per_night' } },
  components: [
    { code: 'BASE', label: 'Base duty charges', quantityExpr: '1', rate: base, unit: 'duty', taxCategory: 'taxable', clauseRef: 'DEMO' },
    { code: 'EXKM', label: 'Extra km', quantityExpr: 'extra_km', rate: '18', unit: 'km', taxCategory: 'taxable', clauseRef: 'DEMO' },
    { code: 'EXHR', label: 'Extra hours', quantityExpr: 'extra_hours', rate: '200', unit: 'hr', taxCategory: 'taxable', clauseRef: 'DEMO' },
    { code: 'NIGHT', label: 'Night charge', quantityExpr: 'night_count', rate: '250', unit: 'night', taxCategory: 'taxable', clauseRef: 'DEMO' },
    { code: 'TOLL', label: 'Toll', kind: 'reimbursement', quantityExpr: 'toll', rate: '1', taxCategory: 'non_taxable' },
    { code: 'PARK', label: 'Parking', kind: 'reimbursement', quantityExpr: 'parking', rate: '1', taxCategory: 'non_taxable' },
  ],
});
for (const [name, cat, base] of [['Innova package (DEMO)', innova, '3200'], ['Dzire package (DEMO)', dzire, '2600']] as const) {
  const s = await call('POST', '/rate-schemes', { contract_id: contract, name });
  const v = await call('POST', `/rate-schemes/${s.id}/versions`, { effective_from: '2025-04-01', vehicle_category_ids: [cat], config: cfg(base), clause_ref: 'DEMO' });
  await call('POST', `/rate-versions/${v.id}/submit`, {});
  await call('POST', `/rate-versions/${v.id}/approve`, {}, 'approver');
}
await call('POST', '/templates', { client_id: client, contract_id: contract, name: 'DEMO monthly bill' });
const tv = (await call('GET', `/templates?clientId=${client}`))[0].versions[0].id;
await call('POST', `/template-versions/${tv}/approve`, { previewReviewed: true }, 'approver');

// September duties for three vehicles
const rows: Record<string, unknown>[] = [];
const vehicles = [['DL1C0012', innova], ['0099', dzire], ['DL3CAB0456', innova]] as const;
for (let day = 1; day <= 30; day++) {
  const dd = `2025-09-${String(day).padStart(2, '0')}`;
  if (new Date(`${dd}T00:00:00Z`).getUTCDay() === 0) continue;
  vehicles.forEach(([reg, cat], i) => {
    const km = 55 + ((day * 17 + i * 23) % 90);
    const startKm = 10000 * (i + 1) + day * 150;
    const late = (day + i) % 7 === 0;
    const endH = 17 + ((day + i) % 4);
    rows.push({
      contractId: contract, dutyDate: dd, vehicleCategoryId: cat, vehicleRegNo: reg, dutyTypeCode: 'LOCAL', driverName: ['Ramesh', 'Suresh', 'Mahesh'][i], fieldOfficer: ['Section Officer A', 'Deputy Director B', 'Under Secretary C'][i],
      startKm: String(startKm), endKm: String(startKm + km), startAt: `${dd} 09:00`,
      endAt: late ? `2025-09-${String(day + 1).padStart(2, '0')} 00:30` : `${dd} ${endH}:${day % 2 ? '15' : '45'}`,
      toll: day % 5 === 0 ? '120' : null, parking: day % 6 === 0 ? '60' : null, vendorName: 'Own fleet',
    });
  });
}
await call('POST', '/duties/bulk', { rows }, 'operator');
await call('POST', '/bills', { contract_id: contract, period_start: '2025-09-01', period_end: '2025-09-30', bill_date: '2025-10-01' }, 'operator');
console.log(`Demo data created: ${rows.length} duties. Demo logins were written to ${envFile}`);
await app.close();
await db.close();
